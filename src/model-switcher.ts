/**
 * The dock picker shows the model that actually handled the latest chat turn.
 * It is also a provider/model switcher; the Ollama fallback setting is kept
 * separately from whatever free model OpenRouter happened to route to.
 */
export type ChatProvider = "local" | "auto" | "openrouter" | "gemini";
export type ModelSwitcherSettings = {
  provider: ChatProvider;
  model: string;
  openrouterModel: string;
  geminiModel: string;
};
export type RoutedReply = {
  model: string;
  provider?: ChatProvider;
  fallbackReason?: string | null;
};
export type ModelSwitcherStatus = {
  label: string;
  title: string;
  /** True only after a real cloud response, not merely selecting Auto. */
  cloudActive: boolean;
};

export function modelSwitcherStatus(
  settings: ModelSwitcherSettings,
  lastReply?: RoutedReply,
  busy = false,
  activity = ""
): ModelSwitcherStatus {
  const local = settings.model;
  if (busy && settings.provider === "auto" && activity.startsWith("Manuscript review: local Ollama")) {
    return {label:`● Local · ${local} · reviewing manuscript…`,
      title:"Auto routes full Notion manuscript reviews to local Ollama instead of the unpredictable OpenRouter/free pool.",
      cloudActive:false};
  }
  if (busy && settings.provider === "auto" && activity.startsWith("Cloud fallback:")) {
    return {label:`↩ Local · ${local} (fallback)`,
      title:`Switching from OpenRouter to local Ollama: ${activity}`,cloudActive:false};
  }
  if (busy) {
    if (settings.provider === "auto" || settings.provider === "openrouter") {
      return {label:"☁ OpenRouter · responding…",
        title:"OpenRouter is attempting this chat turn. The final model may differ from the configured free router.",
        cloudActive:false};
    }
    if (settings.provider === "gemini") {
      return {label:"☁ Gemini · responding…",
        title:`Gemini request using ${settings.geminiModel}`,cloudActive:false};
    }
    return {label:`Local · ${local} · responding…`,title:"Ollama generating locally",cloudActive:false};
  }
  // Never show a model from a previous provider after changing the setting.
  // Older archived diagnostics might lack provider; infer only clear cases.
  const matches = lastReply && (lastReply.provider === settings.provider ||
    (!lastReply.provider && (
      settings.provider === "auto" && (lastReply.model.startsWith("OpenRouter ") || !!lastReply.fallbackReason) ||
      settings.provider === "openrouter" && lastReply.model.startsWith("OpenRouter ") ||
      settings.provider === "gemini" && lastReply.model.startsWith("Gemini ") ||
      settings.provider === "local" && lastReply.model === local
    )));
  if (matches && lastReply) {
    if (lastReply.fallbackReason) {
      return {label:`↩ Local · ${lastReply.model} (fallback)`,
        title:`Last reply was generated by local Ollama ${lastReply.model}. Cloud fallback: ${lastReply.fallbackReason}`,
        cloudActive:false};
    }
    if (lastReply.model.startsWith("OpenRouter ")) {
      const routed = lastReply.model.slice("OpenRouter ".length);
      return {label:`☁ OpenRouter · ${routed}`,
        title:`Last reply used OpenRouter model: ${routed}. This may change on the next request.`,
        cloudActive:true};
    }
    if (lastReply.model.startsWith("Gemini ")) {
      const routed = lastReply.model.slice("Gemini ".length);
      return {label:`☁ Gemini · ${routed}`,
        title:`Last reply used Gemini model: ${routed}`,cloudActive:true};
    }
    if (lastReply.model === local) {
      return {label:`● Local · ${local}`,
        title:`Last reply used Ollama ${local}`,cloudActive:false};
    }
  }
  if (settings.provider === "auto") {
    return {label:"☁ Auto · OpenRouter → Ollama",
      title:`Auto tries free OpenRouter (${settings.openrouterModel}) and falls back to local Ollama ${local}. No reply in this mode yet.`,
      cloudActive:false};
  }
  if (settings.provider === "openrouter") {
    return {label:`☁ OpenRouter · ${settings.openrouterModel}`,
      title:"OpenRouter cloud-only mode. The model shown is the configured route until a response identifies the actual model.",
      cloudActive:false};
  }
  if (settings.provider === "gemini") {
    return {label:`☁ Gemini · ${settings.geminiModel}`,
      title:"Gemini cloud-only mode. No reply from this mode yet.",cloudActive:false};
  }
  return {label:`● Local · ${local}`,title:`Ollama ${local}`,cloudActive:false};
}

/** User-selected dock option; status items are display-only. */
export function modelSwitcherChoice(value: string, installed: readonly string[]):
  | {provider:"local";model:string}
  | {provider:"auto"|"openrouter"|"gemini"}
  | null {
  if (value === "auto" || value === "openrouter" || value === "gemini") {
    return {provider:value};
  }
  if (value.startsWith("local:")) {
    const model=value.slice("local:".length);
    if (installed.includes(model)) return {provider:"local",model};
  }
  return null;
}
