package dev.capnolithyl.mikan.launcher;
import java.time.LocalDate;
public final class DreamRulesTest {
    private static void check(boolean condition){if(!condition)throw new AssertionError();}
    public static void main(String[] args){
        check(DreamRules.period(5)==DreamRules.Period.NIGHT);
        check(DreamRules.period(6)==DreamRules.Period.MORNING);
        check(DreamRules.period(10)==DreamRules.Period.MORNING);
        check(DreamRules.period(11)==DreamRules.Period.DAY);
        check(DreamRules.period(17)==DreamRules.Period.EVENING);
        check(DreamRules.period(22)==DreamRules.Period.NIGHT);
        LocalDate thanksgiving=LocalDate.of(2026,11,26);
        check(DreamRules.artwork(DreamRules.SLEEPY,thanksgiving,DreamRules.Period.DAY)==DreamRules.Period.NIGHT);
        check(DreamRules.artwork(DreamRules.DAY,thanksgiving,DreamRules.Period.NIGHT)==DreamRules.Period.DAY);
        check(DreamRules.artwork(DreamRules.RANDOM,thanksgiving,DreamRules.Period.DAY)==DreamRules.artwork(DreamRules.RANDOM,thanksgiving,DreamRules.Period.DAY));
        check(DreamRules.holiday(DreamRules.AUTO,true,thanksgiving,DreamRules.Period.DAY)!=null);
        check(DreamRules.holiday(DreamRules.AUTO,true,thanksgiving,DreamRules.Period.NIGHT)==null);
        check(DreamRules.holiday(DreamRules.DAY,true,thanksgiving,DreamRules.Period.DAY)==null);
        check(DreamRules.holiday(DreamRules.AUTO,false,thanksgiving,DreamRules.Period.DAY)==null);
        for(long minute=-100;minute<100;minute++){check(Math.abs(DreamRules.shiftX(minute))<=2);check(Math.abs(DreamRules.shiftY(minute))<=2);}
        check(DreamRules.dedicated(DreamRules.Period.MORNING).equals("portraits/dream/morning.webp"));
        check(DreamRules.background(DreamRules.TINTED,DreamRules.COZY)==DreamRules.TINTED);
        check(DreamRules.background(DreamRules.TINTED,DreamRules.MINIMAL)==DreamRules.BLACK);
        check(DreamRules.background(DreamRules.WARM,DreamRules.DEEP)==DreamRules.BLACK);
        check(DreamRules.background(-1,DreamRules.COZY)==DreamRules.BLACK);
        check(DreamRules.background(99,DreamRules.COZY)==DreamRules.TINTED);
        check(DreamRules.feather(0)<DreamRules.feather(1)&&DreamRules.feather(1)<DreamRules.feather(2));
        check(DreamRules.palette(DreamRules.Period.DAY)[1]!=DreamRules.palette(DreamRules.Period.NIGHT)[1]);
        int[] uniform={0xffa06530,0xffa06530,0xffa06530,0xffa06530};
        check(java.util.Arrays.equals(uniform,DreamRules.blurRgb(uniform,2,2,3)));
        int[] sharp={0xff000000,0xffffffff,0xff000000};
        int[] soft=DreamRules.blurRgb(sharp,3,1,1);
        check((soft[0]&255)>0&&(soft[1]&255)<255&&soft[0]==soft[2]);
        check(sharp[1]==0xffffffff);
        check(DreamRules.blurRgb(new int[]{0xff123456},1,1,24)[0]==0xff123456);
        check(DreamRules.motion(2,DreamRules.COZY,true)==2);
        check(DreamRules.motion(2,DreamRules.MINIMAL,true)==0);
        check(DreamRules.motion(2,DreamRules.DEEP,true)==0);
        check(DreamRules.motion(2,DreamRules.COZY,false)==0);
        check(DreamRules.motion(-1,DreamRules.COZY,true)==0);
        check(DreamRules.frameDelay(0,DreamRules.Period.DAY)==0);
        check(DreamRules.frameDelay(1,DreamRules.Period.NIGHT)>DreamRules.frameDelay(1,DreamRules.Period.DAY));
        check(DreamRules.particleCount(2,DreamRules.Period.DAY)>DreamRules.particleCount(1,DreamRules.Period.DAY));
        check(DreamRules.particleCount(0,DreamRules.Period.NIGHT)==0);
        check(DreamRules.phase(12000,10000,3000)==.5f);
        check(DreamRules.phase(-1000,10000,0)==.9f);
        check(DreamRules.envelope(0)==0&&DreamRules.envelope(.5f)==1&&DreamRules.envelope(1)<.0001f);
        check(DreamRules.particleCount(2,DreamRules.Period.DAY)==16);
        check(DreamRules.particleRadius(2,DreamRules.Period.DAY,0)>=.0048f);
        check(DreamRules.particleRadius(2,DreamRules.Period.DAY,0)>DreamRules.particleRadius(1,DreamRules.Period.DAY,0));
        check(DreamRules.particleAlpha(2,DreamRules.Period.DAY)>=200);
        check(DreamRules.particleAlpha(2,DreamRules.Period.NIGHT)<DreamRules.particleAlpha(2,DreamRules.Period.DAY));
        check(DreamRules.particleAlpha(0,DreamRules.Period.DAY)==0);
        check(DreamRules.particleDuration(2,0)<DreamRules.particleDuration(1,0));
        long now=100000000L;
        check(DreamRules.weatherFreshness(0,now)==0);
        check(DreamRules.weatherFreshness(now+1,now)==0);
        check(DreamRules.weatherFreshness(now,now)==1);
        check(DreamRules.weatherFreshness(now-30*60*1000L+1,now)==1);
        check(DreamRules.weatherFreshness(now-30*60*1000L,now)==2);
        check(DreamRules.weatherFreshness(now-6*60*60*1000L,now)==0);
        check(DreamRules.temperature(0,true).equals("32°F"));
        check(DreamRules.temperature(-5,false).equals("-5°C"));
        check(DreamRules.alarmDay(thanksgiving,thanksgiving).equals("Today"));
        check(DreamRules.alarmDay(thanksgiving,thanksgiving.plusDays(1)).equals("Tomorrow"));
        check(!DreamRules.alarmDay(thanksgiving,thanksgiving.plusDays(3)).equals("Tomorrow"));
        check(DreamRules.batteryPercent(0,100)==0);
        check(DreamRules.batteryPercent(100,100)==100);
        check(DreamRules.batteryPercent(92,100)==92);
        check(DreamRules.batteryPercent(2,3)==67);
        check(DreamRules.batteryPercent(-1,100)==-1);
        check(DreamRules.batteryPercent(1,0)==-1);
        check(DreamRules.batteryPercent(101,100)==-1);
        check(DreamRules.chargeFinishAt(now,45*60000L)==now+45*60000L);
        check(DreamRules.chargeFinishAt(now,-1)==-1);
        check(DreamRules.chargeFinishAt(now,0)==-1);
        check(DreamRules.chargeFinishAt(now,Long.MAX_VALUE)==-1);
        check(DreamRules.chargeFinishAt(0,60000)==-1);
        System.out.println("DreamRules tests passed");
    }
}
